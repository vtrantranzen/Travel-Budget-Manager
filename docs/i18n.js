  function storage() {
    // __LS is installed by the bootstrap in <head>; fall back if absent.
    try { return (typeof __LS !== 'undefined' && __LS) ? __LS : window.localStorage; }
    catch (e) { return { getItem: function () { return null; }, setItem: function () {} }; }
  }

  function detect() {
    try {
      var saved = storage().getItem(STORE_KEY);
      if (saved && DICT[saved]) return saved;
    } catch (e) {}
    var nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
    var code = String(nav).slice(0, 2).toLowerCase();
    return DICT[code] ? code : 'en';
  }

