    init: function () {
      this.lang = detect();
      this.applyAll();
      return this.lang;
    },

    set: function (lang) {
      if (!DICT[lang]) return;
      this.lang = lang;
      try { storage().setItem(STORE_KEY, lang); } catch (e) {}
      this.applyAll();
      // Let the app re-render anything drawn from JS templates.
      try { window.dispatchEvent(new CustomEvent('languagechange-app', { detail: lang })); } catch (e) {}
    },

    locale:      function () { return (LANGS[this.lang] || LANGS.en).locale; },
    symbolAfter: function () { return !!(LANGS[this.lang] || LANGS.en).symbolAfter; },

    // Missing keys fall back to English, then to the key itself, so a gap
    // shows as English rather than a blank or a crash.
    t: function (key, vars) {
      var s = (DICT[this.lang] && DICT[this.lang][key]);
      if (s === undefined) s = (DICT.en && DICT.en[key]);
      if (s === undefined) return key;
      if (vars) {
        Object.keys(vars).forEach(function (k) {
          s = s.split('{' + k + '}').join(String(vars[k]));
        });
      }
      return s;
    },

    apply: function (root) {
      var scope = root || document;
      var self = this;
      scope.querySelectorAll('[data-i18n]').forEach(function (el) {
        el.textContent = self.t(el.getAttribute('data-i18n'));
      });
      // Blocks whose translation carries markup (<br>, <strong>, links).
      // Dictionary content is app-authored, never user input.
      scope.querySelectorAll('[data-i18n-html]').forEach(function (el) {
        el.innerHTML = self.t(el.getAttribute('data-i18n-html'));
      });
      ['placeholder', 'title', 'aria-label'].forEach(function (attr) {
        scope.querySelectorAll('[data-i18n-' + attr + ']').forEach(function (el) {
          el.setAttribute(attr, self.t(el.getAttribute('data-i18n-' + attr)));
        });
      });
    },

    applyAll: function () {
      try {
        document.documentElement.setAttribute('lang', this.lang);
        var ttl = document.querySelector('title');
        if (ttl) ttl.textContent = this.t('app.name');
        this.apply(document);
        var self = this;
        document.querySelectorAll('.lang-select').forEach(function (sel) {
          sel.value = self.lang;
        });
      } catch (e) {}
    }
